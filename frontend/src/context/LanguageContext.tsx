interface LanguageContextType {
  language: Language;
  setLanguage: (lang: Language) => void;
  t: typeof translations['th'];
  formatDate: (date: string | Date, options?: Intl.DateTimeFormatOptions) => string;
}

const LanguageContext = createContext<LanguageContextType | undefined>(undefined);

export const LanguageProvider: React.FC<{ children: React.ReactNode }> = ({ children }) => {
  const [language, setLanguageState] = useState<Language>(() => {
    const saved = localStorage.getItem('internflow_lang');
    return (saved === 'en' || saved === 'th') ? saved : 'th';
  });

  const setLanguage = (lang: Language) => {
    setLanguageState(lang);
    localStorage.setItem('internflow_lang', lang);
  };

  const formatDate = (dateInput: string | Date, options?: Intl.DateTimeFormatOptions): string => {
    const d = typeof dateInput === 'string' ? new Date(dateInput) : dateInput;
    if (isNaN(d.getTime())) return '';

    const defaultOptions: Intl.DateTimeFormatOptions = {
      weekday: 'long',
      year: 'numeric',
      month: 'short',
      day: 'numeric'
    };

    const finalOptions = options || defaultOptions;

    if (language === 'th') {
      return d.toLocaleDateString('th-TH', finalOptions);
    } else {
      return d.toLocaleDateString('en-US', finalOptions);
    }
  };

  return (
    <LanguageContext.Provider value={{ language, setLanguage, t: translations[language], formatDate }}>
      {children}
    </LanguageContext.Provider>
  );
};

export const useLanguage = (): LanguageContextType => {
  const context = useContext(LanguageContext);
  if (!context) {
    throw new Error('useLanguage must be used within a LanguageProvider');
  }
  return context;
};

export const LanguageSwitcher: React.FC<{ className?: string }> = ({ className = '' }) => {
  const { language, setLanguage } = useLanguage();

  return (
    <div className={`inline-flex items-center p-0.5 rounded-xl bg-slate-100 border border-slate-200/80 shadow-2xs ${className}`}>
      <button
        type="button"
        onClick={() => setLanguage('th')}
        className={`px-2.5 py-1 text-xs font-black rounded-lg transition-all cursor-pointer ${
          language === 'th'
            ? 'bg-white text-emerald-700 shadow-xs scale-100'
            : 'text-slate-500 hover:text-slate-800'
        }`}
        title="ภาษาไทย"
      >
        TH
      </button>
      <button
        type="button"
        onClick={() => setLanguage('en')}
        className={`px-2.5 py-1 text-xs font-black rounded-lg transition-all cursor-pointer ${
          language === 'en'
            ? 'bg-white text-emerald-700 shadow-xs scale-100'
            : 'text-slate-500 hover:text-slate-800'
        }`}
        title="English"
      >
        EN
      </button>
    </div>
  );
};
